#!/usr/bin/env node
/* Turn a footage track's seamless loop into a base64 data: URI.
 *
 * Footage in a <video> loaded from a plain file:// path is treated as
 * cross-origin by browsers, so WebGL refuses to sample it (the frame comes out
 * black). A data: URI is same-origin — it samples cleanly and needs no server —
 * so this is how a real-footage clip gets "painlessly" into a visual-core scene
 * and therefore into player.html / dist for the show.
 *
 *   node build-video-datauri.js 06-cave-human            # auto-picks the loop in assets/
 *   node build-video-datauri.js 06-cave-human my-clip.mp4
 *
 * It writes  tracks/<track>/video-datauri.js  containing
 *   window.IL_VIDEO = "data:video/mp4;base64,....";
 * index.html loads that (when present) and passes it to Ambient.start; build.js
 * then inlines it into the flattened dist file, which is fully self-contained
 * and plays offline from file://. The generated file is large and gitignored —
 * the editable source of truth is the loop in assets/. Rerun after re-cutting it.
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const TRACKS = path.join(ROOT, 'tracks');
const VIDEO_EXT = ['.mp4', '.webm', '.mov', '.m4v', '.ogv'];
const MIME = { '.mp4': 'video/mp4', '.m4v': 'video/mp4', '.mov': 'video/quicktime',
               '.webm': 'video/webm', '.ogv': 'video/ogg' };

const track = process.argv[2];
if (!track) {
  console.error('usage: node build-video-datauri.js <track-dir> [clip-file]');
  console.error('  e.g. node build-video-datauri.js 06-cave-human');
  process.exit(1);
}

const assets = path.join(TRACKS, track, 'assets');
if (!fs.existsSync(assets)) { console.error('no assets/ in tracks/' + track); process.exit(1); }

let clip = process.argv[3];
if (clip) {
  clip = path.isAbsolute(clip) ? clip : path.join(assets, clip);
} else {
  // auto-pick: prefer a file whose name mentions "loop", else the largest video
  const vids = fs.readdirSync(assets)
    .filter(f => VIDEO_EXT.includes(path.extname(f).toLowerCase()))
    .map(f => ({ f, full: path.join(assets, f), size: fs.statSync(path.join(assets, f)).size }));
  if (!vids.length) { console.error('no video files in ' + assets); process.exit(1); }
  const loops = vids.filter(v => /loop/i.test(v.f));
  clip = (loops[0] || vids.sort((a, b) => b.size - a.size)[0]).full;
}
if (!fs.existsSync(clip)) { console.error('clip not found: ' + clip); process.exit(1); }

const mime = MIME[path.extname(clip).toLowerCase()] || 'video/mp4';
const b64 = fs.readFileSync(clip).toString('base64');
const out = path.join(TRACKS, track, 'video-datauri.js');
fs.writeFileSync(out,
  '/* GENERATED by build-video-datauri.js from assets/' + path.basename(clip) + ' — do not edit, gitignored. */\n' +
  'window.IL_VIDEO = "data:' + mime + ';base64,' + b64 + '";\n');

const mb = n => (n / 1024 / 1024).toFixed(1) + ' MB';
console.log('wrote', path.relative(ROOT, out),
  '(' + mb(Buffer.byteLength(b64)) + ' base64 from a ' + mb(fs.statSync(clip).size) + ' clip)');
console.log('now open tracks/' + track + '/index.html, or  node build.js ' + track + '  for a self-contained dist file.');
